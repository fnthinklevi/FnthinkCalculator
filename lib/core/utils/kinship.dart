  static bool isToken(String value) => tokens.contains(value);

  static String describe(List<String> chain) {
    if (chain.isEmpty) return '我';
    final buffer = StringBuffer('我的');
    for (var index = 0; index < chain.length; index++) {
      if (index > 0) buffer.write('的');
      buffer.write(_description[chain[index]] ?? chain[index]);
    }
    return buffer.toString();
  }

  static String? direct(List<String> chain) {
    if (chain.isEmpty) return '我';
    return _direct[chain.join()];
  }

  static String? reciprocal(List<String> chain) {
    if (chain.isEmpty) return '我';
    return _reciprocal[chain.join()];
  }
